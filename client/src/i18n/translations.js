export const toBengaliNumber = (num, lang = 'en') => {
  if (lang !== 'bn') return num;
  const bengaliDigits = ['০', '১', '২', '৩', '৪', '৫', '৬', '৭', '৮', '৯'];
  return String(num).replace(/[0-9]/g, (w) => bengaliDigits[+w]);
};
